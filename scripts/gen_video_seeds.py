def gen_episode_url(grade: int, subject: str, version: str, semester: str,
                    chapter: str, episode: str) -> dict:
    """生成一个 episode 的种子数据"""
    # 用 episode 名称作 keyword
    kw = episode
    return {
        "grade": grade,
        "subject": subject,
        "version": version,
        "semester": semester,
        "chapter": chapter,
        "episode": episode,
        "search_url": url(kw),
        "chapter_listing_url": chapter_listing_url(chapter),
        "week_index": 0,  # 在 caller 覆盖
        "importance": 3,
        "knowledge_point_codes": [],
        "description": f"{(version)}{grade} 年级{(subject_label(subject))}{(semester_label(semester))} - {chapter}: {episode}",
        "verified": False,
    }


def subject_label(s: str) -> str:
    return {"math": "数学", "chinese": "语文", "english": "英语", "science": "科学"}.get(s, s)


def semester_label(s: str) -> str:
    return {"2025-fall": "2025 秋", "2025-spring": "2025 春"}.get(s, s)


def gen_for_grade_subject(grade: int, subject: str, version: str, semester: str,
                          chapters: list) -> list:
    """为一组 (grade, subject, version, semester) 生成所有 episode 记录"""
    out = []
    for ch, week, importance, episodes in chapters:
        for ep in episodes:
            rec = gen_episode_url(grade, subject, version, semester, ch, ep)
            rec["week_index"] = week
            rec["importance"] = importance
            out.append(rec)
    return out


def main():
    total_files = 0
    total_videos = 0
    for grade, subjects in CURRICULUM.items():
        for subject, versions in subjects.items():
            for version, semesters in versions.items():
                for semester, chapters in semesters.items():
                    fname = f"seed_g{grade}_{subject}_{semester}.json"
                    fpath = OUT_DIR / fname
                    videos = gen_for_grade_subject(grade, subject, version, semester, chapters)
                    payload = {
                        "version": "1.0",
                        "updated_at": "2026-07-31",
                        "note": f"{version}{grade} 年级 {subject_label(subject)} {semester_label(semester)} 空中课堂微课索引 (按章节)。每条 episode 是搜索关键词, 朋友点开跳到 basic.sh.smartedu.cn。",
                        "source": AIRCLASS,
                        "videos": videos,
                    }
                    fpath.write_text(json.dumps(payload, ensure_ascii=False, indent=2))
                    total_files += 1
                    total_videos += len(videos)
                    print(f"  ✓ {fname}: {len(videos)} videos ({len(chapters)} chapters)")
    print(f"\n📦 {total_files} files, {total_videos} videos")


if __name__ == "__main__":
    main()
